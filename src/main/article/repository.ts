import type { Article } from './model'

function domainError(code: string, message: string): Error & { code: string } {
  return Object.assign(new Error(message), { code })
}

/** Returned when an article does not exist. */
export const errNotFound = domainError('errNotFound', 'article not found')

/** Returned when an article title is already used in the same story. */
export const errTitleTaken = domainError(
  'errTitleTaken',
  'article title already taken in this story'
)

/**
 * Port for article persistence.
 *
 * `create` persists the article and returns the stored entity: the ID is
 * generated by the model constructor, and createdAt/updatedAt come from the
 * database.
 */
export interface ArticleRepository {
  create(article: Article): Promise<Article>
  get(id: string): Promise<Article>
  listByStory(storyID: string): Promise<Article[]>
  list(): Promise<Article[]>
  update(article: Article): Promise<Article>
  delete(id: string): Promise<void>
}
